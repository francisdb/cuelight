//! Generic show player: load a show file or a show folder, list what it
//! can do, drive it interactively or from a driver file.
//!
//! ```sh
//! cargo run --example player -- path/to/show[.json] [path/to/driver.json]
//! ```
//!
//! A show folder is the self-contained form of a show:
//!
//! ```text
//! myshow/
//!   show.json           the show document (required)
//!   test-driver.json    optional driver, picked up automatically
//!   assets/             PNGs (any color type or bit depth) registered as
//!                       images by filename stem
//!     fonts/            bitmap fonts (.fnt plus page PNGs), registered by
//!                       .fnt filename stem
//! ```
//!
//! A bare `.json` path plays a single show file instead. With no arguments
//! the bundled minigolf show plays. The player inspects the model and
//! prints its actions (trigger names) and variables to the console: type
//! an action's number or name to fire it, `name=value` to set a variable,
//! `q` to quit. Digit keys in the window fire actions too, escape quits.
//!
//! A driver file scripts the same commands with delays, standing in for a
//! live host; next to a loose show file the convention is
//! `<show>.test-driver.json` (see `examples/shows/`):
//!
//! ```json
//! {
//!   "loop": true,
//!   "steps": [
//!     { "set": { "score": 0 } },
//!     { "wait": 0.5 },
//!     { "trigger": "go" }
//!   ]
//! }
//! ```
//!
//! Console and keyboard input keep working while a driver runs.
//!
//! Images a show references but nobody registered are logged as warnings
//! at load and skipped (the slideshow's are generated by its own host
//! code, so they stay missing here).

